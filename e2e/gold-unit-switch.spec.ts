import { test, expect } from '@playwright/test';
import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
import { calculateProfessional } from '../src/server/professional-calculator';

test('gold and trade inputs convert once and preserve canonical calculation values', async ({ page }) => {
  const bundle = await build({ stdin: { contents: `import {createRoot} from 'react-dom/client';
    import {ProfessionalCalculator} from './src/components/professional-calculator';
    import {TradeCalculator} from './src/components/trade-calculator';
    import {defaultCalculatorAccessPolicy} from './src/lib/calculator-access';
    import {defaultCalculatorNavigation} from './src/lib/calculator-navigation';
    const snapshot={mode:'live',status:'unavailable',quotes:[]};
    createRoot(document.getElementById('root')).render(<><ProfessionalCalculator snapshot={snapshot} accessPolicy={defaultCalculatorAccessPolicy} navigation={defaultCalculatorNavigation}/><div id="trade"><TradeCalculator operation="quickTrade" snapshot={snapshot}/></div></>);`, loader: 'tsx', resolveDir: process.cwd() }, bundle: true, write: false, jsx: 'automatic', define: { 'process.env': '{}', 'process.env.NODE_ENV': '"production"' } });
  const css = (await Promise.all(['globals.css', 'theme.css', 'calculator/calculator.css'].map(file => readFile(`src/app/${file}`, 'utf8')))).join('\n');
  await page.route('**/__gold-unit-fixture', route => route.fulfill({ contentType: 'text/html', body: `<html lang="fa" dir="rtl" class="site-ready"><meta name="viewport" content="width=device-width,initial-scale=1"><style>${css}</style><main id="root" style="max-width:980px;margin:16px auto;width:calc(100% - 32px)"></main><script>${bundle.outputFiles[0].text.replaceAll('</script', '<\\/script')}</script></html>` }));
  let sent: any;
  await page.route('**/api/public/calculator/professional', route => {
    sent = route.request().postDataJSON();
    return route.fulfill({ json: calculateProfessional(sent, { mode: 'live', status: 'unavailable', quotes: [] }) });
  });
  await page.goto('/__gold-unit-fixture');
  const gold = page.locator('.professional-calculator');
  await gold.getByRole('button', { name: 'سرمایه به طلا', exact: true }).click();
  await gold.getByRole('textbox', { name: 'سرمایه', exact: true }).fill('100000000');
  await gold.getByRole('textbox', { name: /قیمت (گرم|مثقال) طلای ۱۸ عیار/ }).fill('10000000');
  await gold.getByRole('group', { name: 'واحد طلای ۱۸ عیار' }).getByRole('button', { name: 'مثقال', exact: true }).click();
  await expect(gold.getByRole('textbox', { name: /قیمت (گرم|مثقال) طلای ۱۸ عیار/ })).toHaveValue('43,318,000');
  await gold.getByRole('button', { name: 'محاسبه', exact: true }).click();
  expect(sent.inputs.gram.value).toBe(10000000);
  await expect(page.getByRole('dialog', { name: 'نتیجه محاسبه' })).toContainText('مثقال');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await gold.getByRole('button', { name: 'طلای خالص', exact: true }).click();
  await gold.getByRole('group', { name: 'واحد طلای ۱۸ عیار' }).getByRole('button', { name: 'مثقال', exact: true }).click();
  await gold.getByRole('textbox', { name: 'وزن ناخالص', exact: true }).fill('1');
  await gold.getByRole('textbox', { name: 'عیار', exact: true }).fill('750');
  await gold.getByRole('textbox', { name: /قیمت (گرم|مثقال) طلای ۱۸ عیار/ }).fill('43318000');
  await gold.getByRole('button', { name: 'محاسبه', exact: true }).click();
  expect(sent.inputs.weight.value).toBe(4.3318);
  await expect(page.getByRole('dialog', { name: 'نتیجه محاسبه' })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const trade = page.locator('#trade');
  await trade.getByRole('textbox', { name: 'قیمت فعلی', exact: true }).fill('10000000');
  await trade.getByRole('textbox', { name: 'قیمت ورود', exact: true }).fill('9000000');
  await trade.getByRole('textbox', { name: 'وزن معامله', exact: true }).fill('4.3318');
  await trade.getByRole('textbox', { name: 'قیمت هدف', exact: true }).fill('11000000');
  await trade.getByRole('textbox', { name: 'حد ضرر', exact: true }).fill('8000000');
  await trade.getByRole('group', { name: 'واحد طلای ۱۸ عیار' }).getByRole('button', { name: 'مثقال', exact: true }).click();
  await expect(trade.getByRole('textbox', { name: 'وزن معامله', exact: true })).toHaveValue('4.3318');
  await expect(trade.getByRole('textbox', { name: 'قیمت ورود', exact: true })).toHaveValue('38,986,200');
  await trade.getByRole('textbox', { name: 'وزن معامله', exact: true }).press('End');
  await trade.getByRole('textbox', { name: 'وزن معامله', exact: true }).pressSequentially('5');
  await expect(trade.getByRole('textbox', { name: 'وزن معامله', exact: true })).toHaveValue('4.33185');
  await trade.getByRole('button', { name: 'محاسبه', exact: true }).click();
  expect(sent.trade.entry).toBe(9000000);
  expect(sent.trade.weight).toBeCloseTo(4.33185);
  await expect(page.getByRole('dialog', { name: 'نتیجه سناریوی معامله' })).toContainText('گرم');
  const report = page.getByRole('dialog', { name: 'نتیجه سناریوی معامله' });
  for (const label of ['میانگین وزنی', 'بازده فعلی', 'سربه‌سر با هزینه‌ها', 'فاصله قیمت فعلی تا سربه‌سر', 'بازده در هدف', 'بازده در حد ضرر', 'نسبت فاصله هدف به حد ضرر', 'نسبت سود به ریسک خالص']) {
    await expect(report.getByText(label, { exact: true })).toHaveCount(0);
  }
  await expect(report.getByText('سود/زیان خالص در هدف', { exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await trade.getByRole('textbox', { name: 'وزن معامله', exact: true }).fill('104');
  await trade.getByRole('textbox', { name: 'قیمت ورود', exact: true }).fill('113020000');
  await trade.getByRole('textbox', { name: 'قیمت فعلی', exact: true }).fill('113730000');
  await trade.getByRole('textbox', { name: 'قیمت هدف', exact: true }).fill('115300000');
  await trade.getByRole('textbox', { name: 'حد ضرر', exact: true }).fill('113000000');
  await trade.getByText('کارمزد و هزینه‌ها', { exact: true }).click();
  await trade.getByRole('textbox', { name: 'کارمزد خرید', exact: true }).fill('100000');
  await trade.getByRole('button', { name: 'محاسبه', exact: true }).click();
  expect(sent.trade.weight).toBe(104);
  expect(sent.trade.entry).toBeCloseTo(113020000 / 4.3318, 4);
  const outputs = calculateProfessional(sent, { mode: 'live', status: 'unavailable', quotes: [] }).outputs;
  expect(outputs.find(o => o.label === 'سرمایه با کارمزد خرید')?.value).toBeCloseTo(104 * 113020000 / 4.3318 + 100000, 2);
  expect(outputs.find(o => o.label === 'ارزش فعلی')?.value).toBeCloseTo(104 * 113730000 / 4.3318, 2);
  expect(outputs.find(o => o.label === 'سود/زیان خالص در هدف')?.value).toBeCloseTo(104 * (115300000 - 113020000) / 4.3318 - 100000, 2);
  expect(outputs.find(o => o.label === 'سود/زیان خالص در حد ضرر')?.value).toBeCloseTo(104 * (113000000 - 113020000) / 4.3318 - 100000, 2);
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
});
